#!/usr/bin/env python3
"""Generate registration-client/src/main/resources/application-cein.css.

application-cein.css = MOSIP application.css with the CEIN palette and fonts
                       substituted + tools/theme/cein-overrides.css appended.

Run after editing application.css or cein-overrides.css:
    python3 tools/theme/gen-theme.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "registration/registration-client/src/main/resources"
BASE = RES / "application.css"
OVERRIDES = pathlib.Path(__file__).with_name("cein-overrides.css")
OUT = RES / "application-cein.css"

# MOSIP colour -> CEIN colour (case-insensitive)
PALETTE = {
    "#005baa": "#006B33",  # main blue -> CEIN green
    "#004887": "#00532A",  # dark blue -> dark green
    "#0b6a82": "#006B33",
    "#175768": "#00532A",
    "#22a8c9": "#006B33",
    "#00a6e9": "#006B33",
    "#0286f7": "#006B33",
    "#c9c9c9": "#DCE3E8",  # separators
    "#666666": "#4A5866",  # secondary text
    "#808080": "#4A5866",
    "#f0f0f0": "#F4F6F5",  # backgrounds
    "#f4f4f4": "#F4F6F5",
    "#efefef": "#F4F6F5",
    "#f2f2f2": "#F4F6F5",
    "#ff0000": "#B3261E",  # errors
    "#45a30a": "#00853F",
    "#61ab01": "#00853F",
    "#f57e20": "#8A5300",
}


def main():
    css = BASE.read_text(encoding="utf-8")
    for src, dst in PALETTE.items():
        css = re.sub(re.escape(src), dst, css, flags=re.IGNORECASE)
    css = re.sub(r"-fx-font-family:\s*(Roboto|System)\s*;", "-fx-font-family: 'Inter';", css)
    header = ("/* GENERATED by tools/theme/gen-theme.py - do not edit by hand.\n"
              "   Source: application.css (palette mapped) + tools/theme/cein-overrides.css */\n\n")
    OUT.write_text(header + css + "\n\n" + OVERRIDES.read_text(encoding="utf-8"), encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
